// Send printf to uart1
int __io_putchar(int ch) {
    if (ch == '\n') {
        HAL_UART_Transmit(&huart1, (uint8_t*) "\r", 1, HAL_MAX_DELAY);
    }
    if (HAL_UART_Transmit(&huart1, (uint8_t*) &ch, 1, HAL_MAX_DELAY) != HAL_OK) {
        return -1;
    }
    return ch;
}

// 1. Provide a physical write wrapper (UART DMA / IT)
void write_char_cb(EmbeddedCli *cli, char c) {
    HAL_UART_Transmit(&huart1, (uint8_t*) &c, 1, HAL_MAX_DELAY);
}

// 2. Define a callback function for a command
void on_led_command(EmbeddedCli *cli, char *args, void *context) {
    HAL_GPIO_TogglePin(LED_GPIO_Port, LED_Pin);
    embeddedCliPrint(cli, "LED Toggled!\r\n");
}

void init_console(void) {
    // 3. Initialize CLI with default settings
    EmbeddedCliConfig *config = embeddedCliDefaultConfig();
    config->maxBindingCount = 16;
    cli = embeddedCliNew(config);
    if (cli == NULL) return;

    cli->writeChar = write_char_cb;

    // 4. Bind a command
    embeddedCliAddBinding(cli, (CliCommandBinding ) {
                    .name = "toggle-led",
                    .help = "Toggles the onboard LED",
                    .tokenizeArgs = false,
                    .context = NULL,
                    .binding = on_led_command
            });

    // 5. Start RX DMA & IDLE Line Interrupt
    __HAL_UART_ENABLE_IT(&huart1, UART_IT_IDLE);
    HAL_UART_Receive_DMA(&huart1, rx_dma_buffer, RX_BUFFER_SIZE);
}

// Read received bytes from DMA circular buffer
void process_uart_dma_input(void) {
    if (cli == NULL) return;

    uint16_t current_pos = RX_BUFFER_SIZE - __HAL_DMA_GET_COUNTER(&hdma_usart1_rx);

    if (current_pos != old_pos) {
        if (current_pos > old_pos) {
            for (uint16_t i = old_pos; i < current_pos; i++) {
                embeddedCliReceiveChar(cli, (char)rx_dma_buffer[i]);
            }
        } else {
            for (uint16_t i = old_pos; i < RX_BUFFER_SIZE; i++) {
                embeddedCliReceiveChar(cli, (char)rx_dma_buffer[i]);
            }
            for (uint16_t i = 0; i < current_pos; i++) {
                embeddedCliReceiveChar(cli, (char)rx_dma_buffer[i]);
            }
        }
        old_pos = current_pos;
    }
}

